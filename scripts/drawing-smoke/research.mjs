import { chromium, CHROME, readUrl, openDesk, waitCandles, check } from './common.mjs'
import { readFile } from 'node:fs/promises'
const url = await readUrl()
const browser = await chromium.launch({headless:true,executablePath:CHROME})
try {
  const page=await browser.newPage({viewport:{width:2500,height:1500},timezoneId:'UTC'})
  const openIndicators=async()=>{ if(await page.locator('.dhl-indicator-menu').getAttribute('open')===null) await page.locator('.dhl-indicator-menu summary').click() }
  const errors=[];page.on('pageerror',(error)=>errors.push(error.message))
  await openDesk(page,url)
  await page.getByRole('button',{name:'交易设置',exact:true}).click()
  await page.getByRole('button',{name:'模拟盘',exact:true}).click()
  await page.waitForFunction(()=>window.__dhlStore.get().status?.tradingMode==='paper')
  // Close the environment menu if it remains open.
  if (await page.getByRole('button',{name:'交易设置',exact:true}).getAttribute('aria-expanded') === 'true') await page.getByRole('button',{name:'交易设置',exact:true}).click()
  await page.getByRole('button',{name:'交易设置',exact:true}).click()
  await page.getByRole('button',{name:'交易限额与签名规则',exact:true}).click()
  const limits=page.getByRole('dialog').filter({has:page.getByRole('tablist',{name:'设置分组'})})
  await limits.getByRole('tab',{name:'模拟成本',exact:true}).click()
  await limits.getByRole('spinbutton',{name:'模拟手续费 bps',exact:true}).fill('6')
  await limits.getByRole('button',{name:'保存模拟成本',exact:true}).click()
  await page.waitForFunction(()=>window.__dhlStore.get().status?.paperCosts?.feeBps===6)
  check(true,'paper execution costs save through the public settings dialog')
  await limits.getByRole('button',{name:'关闭',exact:true}).click()
  await page.getByRole('button',{name:/新建交易会话/}).click(); await waitCandles(page)
  const state=()=>page.evaluate(()=> {const s=window.__dhlStore.get();return {workspace:s.workspace,coin:s.activeCoin,interval:s.interval,id:s.activeSessionId,references:s.chartReferences}})
  const first=await state()
  await page.evaluate(() => {
    window.__researchQuotes=[]
    window.__dhlStore.subscribe(() => { for (const quote of window.__dhlStore.get().chartReferences) if (!window.__researchQuotes.some((old)=>old.id===quote.id)) window.__researchQuotes.push(quote) })
  })
  await page.getByRole('combobox',{name:'多周期布局',exact:true}).selectOption('quad')
  await page.waitForFunction(()=>document.querySelectorAll('.dhl-research-pane .dhl-chart-ohlc').length===4,{},{timeout:45000})
  check(await page.locator('.dhl-research-pane').count()===4,'four independent timeframe charts render')
  await page.getByRole('combobox',{name:'多周期布局',exact:true}).selectOption('dual')
  const second=page.locator('.dhl-research-pane').nth(1)
  await second.getByRole('combobox',{name:'研究周期',exact:true}).selectOption('4h')
  await second.locator('.dhl-chart-ohlc').waitFor({timeout:45000})
  let box=await page.locator('.dhl-primary-pane canvas').first().boundingBox()
  await page.mouse.move(box.x+box.width*.45,box.y+70); await page.waitForTimeout(500)
  const pt=Number(await page.locator('.dhl-primary-pane .dhl-chart-ohlc').getAttribute('data-time'))
  const st=Number(await second.locator('.dhl-chart-ohlc').getAttribute('data-time'))
  check(pt>0&&st<=pt&&pt-st<4*3600000,'linked cursor maps to the containing secondary bar',{pt,st})
  await page.mouse.move(box.x+box.width*.6,box.y+100);await page.mouse.down();await page.mouse.move(box.x+box.width*.72,box.y+100,{steps:14});await page.mouse.up();await page.waitForTimeout(1800)
  const ranges=(await state()).workspace.chartRanges
  const a=ranges[`${first.coin}:${first.interval}`],b=ranges[`${first.coin}:4h`]
  check(a&&b&&Math.abs(a.from-b.from)<=4*3600&&Math.abs(a.to-b.to)<=4*3600,'time navigation links both charts in epoch time',{a,b})
  check(await page.evaluate(()=>window.__researchQuotes.length===0),'panning a linked chart does not create quotes')
  await page.getByRole('combobox',{name:'多周期布局',exact:true}).selectOption('single')
  await openIndicators()
  for (const name of ['RSI 14','MACD','BOLL 20','Stochastic','ADX / DMI','OBV']) await page.locator('.dhl-indicator-popover').getByRole('button',{name:new RegExp('^'+name.replace('/','\\/'))}).click()
  await page.getByRole('button',{name:'参数与模板',exact:true}).click()
  const editor=page.getByRole('dialog').filter({has:page.locator('.dhl-study-settings')})
  await editor.getByRole('spinbutton',{name:'RSI 周期',exact:true}).fill('7')
  await editor.getByRole('spinbutton',{name:'MACD 快线',exact:true}).fill('6')
  await editor.getByRole('spinbutton',{name:'BOLL 周期',exact:true}).fill('10')
  await editor.getByRole('spinbutton',{name:'BOLL 标准差倍数',exact:true}).fill('2.5')
  await editor.getByRole('textbox',{name:'指标模板名称',exact:true}).fill('研究冒烟模板')
  await editor.getByRole('button',{name:'另存模板',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('[aria-label="已保存指标模板"]')?.selectedOptions[0]?.textContent==='研究冒烟模板')
  await editor.getByRole('button',{name:'应用指标设置',exact:true}).click()
  if(await page.locator('.dhl-indicator-menu').getAttribute('open')!==null) await page.locator('.dhl-indicator-menu summary').click()
  await page.getByRole('button',{name:'数据窗口',exact:true}).click()
  await page.locator('.dhl-data-window').waitFor()
  check(await page.locator('[data-study="RSI7"]').count()===1,'RSI uses the configured period')
  check(await page.locator('[data-study="MACD 6/26/9"]').count()===1,'MACD uses configured periods')
  check(await page.locator('[data-study="BOLL 10 × 2.5"]').count()===1,'BOLL has an independent basis and multiplier')
  for(const name of ['Stoch %K 14/3','ADX 14/14','OBV'])check(await page.locator(`[data-study="${name}"]`).count()===1,`${name} pane computes values`)
  await page.locator('.dhl-primary-pane canvas').first().scrollIntoViewIfNeeded()
  box=await page.locator('.dhl-primary-pane canvas').first().boundingBox()
  await page.mouse.click(box.x+box.width*.4,box.y+100)
  await page.waitForFunction(()=>window.__researchQuotes.length>0)
  check(await page.evaluate(()=>window.__researchQuotes.at(-1).text.includes('RSI7=')),'point quotes carry configured indicator values')
  await page.getByRole('button',{name:'交易复盘',exact:true}).click()
  await page.locator('.dhl-review-summary').waitFor({timeout:30000})
  check(await page.locator('.dhl-review').getByText(/未模拟/).count()>0,'paper review labels omitted funding')
  await page.getByRole('combobox',{name:'复盘时间范围',exact:true}).selectOption('90')
  await page.locator('.dhl-review-summary').waitFor({timeout:30000})
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出证据 JSON',exact:true}).click()
  const download=await downloadEvent;check(download.suggestedFilename().endsWith('.json'),'review evidence exports as JSON')
  const exported=JSON.parse(await readFile(await download.path(),'utf8'))
  check(exported.evidence.coverage.endTime-exported.evidence.coverage.startTime===90*86400000 && exported.reconciliation.net===null,'90-day evidence preserves exact coverage and unknown paper funding')
  await page.reload();await openDesk(page,url);await waitCandles(page)
  if ((await state()).id !== first.id) { await page.locator(`[data-session-id="${first.id}"]`).click(); await waitCandles(page) }
  check((await state()).workspace.indicatorSettings.rsi.period===7,'indicator parameters survive reload')
  check((await state()).workspace.showDataWindow===true,'data window visibility survives reload')
  await openIndicators();await page.getByRole('button',{name:'参数与模板',exact:true}).click()
  await editor.getByRole('spinbutton',{name:'RSI 周期',exact:true}).fill('0')
  await editor.getByRole('button',{name:'应用指标设置',exact:true}).click()
  check(await editor.getByRole('alert').isVisible(),'invalid periods are rejected')
  const options=await editor.getByRole('combobox',{name:'已保存指标模板',exact:true}).locator('option').allTextContents()
  check(options.includes('研究冒烟模板'),'templates persist on the host')
  const id=await editor.getByRole('combobox',{name:'已保存指标模板',exact:true}).locator('option').filter({hasText:'研究冒烟模板'}).getAttribute('value')
  await editor.getByRole('combobox',{name:'已保存指标模板',exact:true}).selectOption(id)
  check(await editor.getByRole('spinbutton',{name:'RSI 周期',exact:true}).inputValue()==='7','template restores saved parameters')
  await editor.getByRole('button',{name:'应用指标设置',exact:true}).click()
  await page.getByRole('button',{name:/新建交易会话/}).click(); await waitCandles(page)
  check((await state()).workspace.indicatorSettings?.rsi?.period !== 7,'a different session starts with its own parameters')
  await openIndicators();await page.getByRole('button',{name:'参数与模板',exact:true}).click()
  await editor.getByRole('combobox',{name:'已保存指标模板',exact:true}).selectOption(id)
  await editor.getByRole('button',{name:'应用指标设置',exact:true}).click()
  check((await state()).workspace.indicatorSettings.rsi.period===7 && (await state()).workspace.indicators.includes('obv'),'saved templates apply across sessions')
  if(await page.locator('.dhl-indicator-menu').getAttribute('open')!==null) await page.locator('.dhl-indicator-menu summary').click()
  await page.screenshot({path:'/tmp/dsh-hyperliquid-research.png'})
  check(!errors.length,'research controls have no browser runtime errors',errors)
  console.log('research smoke: all checks passed')
} finally {await browser.close()}
