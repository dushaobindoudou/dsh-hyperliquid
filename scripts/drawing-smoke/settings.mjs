// Public UI regression: custody confirmation/persistence and independent tab saves.
// Runs only in the throwaway, unfunded smoke host; never submits a trade.
import { chromium, CHROME, readUrl, openDesk, check } from './common.mjs'
const url = await readUrl()
const browser = await chromium.launch({ headless: true, executablePath: CHROME })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []; page.on('pageerror', (error) => errors.push(error.message))
  await openDesk(page, url)
  await page.waitForFunction(() => window.__dhlStore.get().status?.custody)
  const menu = () => page.getByRole('button', { name: '交易设置', exact: true }).click()
  const status = () => page.evaluate(() => window.__dhlStore.get().status)
  check((await status()).tradingMode === 'live' && (await status()).custody === 'assisted', 'fresh host starts live and assisted')
  const requestManaged = async () => {
    await menu()
    await page.getByRole('group', { name: '托管模式' }).getByRole('button', { name: '全托管', exact: true }).click()
    return page.getByRole('dialog').filter({ has: page.getByRole('button', { name: '开启全托管', exact: true }) })
  }
  let confirmation = await requestManaged()
  await confirmation.waitFor()
  check((await status()).custody === 'assisted', 'live custody does not change before acknowledgement')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  check((await status()).custody === 'assisted', 'cancelling managed confirmation keeps assisted mode')
  confirmation = await requestManaged()
  await confirmation.getByRole('button', { name: '开启全托管', exact: true }).click()
  await page.waitForFunction(() => window.__dhlStore.get().status?.custody === 'managed')
  check(await page.locator('.dhl-badge.managed').isVisible(), 'acknowledged live custody shows the managed badge')
  await page.reload(); await page.locator('.dhl-root').waitFor()
  await page.waitForFunction(() => window.__dhlStore.get().status?.custody === 'managed')
  check(await page.locator('.dhl-badge.managed').isVisible(), 'custody survives a browser refresh')
  await menu()
  await page.getByRole('group', { name: '托管模式' }).getByRole('button', { name: '半托管', exact: true }).click()
  await page.waitForFunction(() => window.__dhlStore.get().status?.custody === 'assisted')
  check(await page.locator('.dhl-badge.managed').count() === 0, 'switching back removes the managed badge')

  await menu()
  await page.getByRole('button', { name: '交易限额与签名规则', exact: true }).click()
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('tablist', { name: '设置分组' }) })
  check(await dialog.getByRole('tab').count() === 3 && await dialog.getByRole('tabpanel').count() === 1, 'limits dialog exposes three tabs and one active panel')
  check(await dialog.getByRole('tab', { name: '交易限额', exact: true }).getAttribute('aria-selected') === 'true', 'limits is the initial tab')
  const before = await status()
  const perOrder = dialog.getByRole('spinbutton', { name: '单笔上限 · USD', exact: true })
  await perOrder.fill(String(before.riskLimits.maxOrderUsd + 1))
  await dialog.getByRole('tab', { name: '模拟成本', exact: true }).click()
  check(await dialog.getByRole('button', { name: '保存限额', exact: true }).count() === 0, 'paper cost footer only saves paper costs')
  await dialog.getByRole('spinbutton', { name: '模拟手续费 bps', exact: true }).fill('6')
  await dialog.getByRole('button', { name: '保存模拟成本', exact: true }).click()
  await page.waitForFunction(() => window.__dhlStore.get().status?.paperCosts?.feeBps === 6)
  check((await status()).riskLimits.maxOrderUsd === before.riskLimits.maxOrderUsd, 'saving costs leaves the unsaved limit draft untouched')
  await dialog.getByRole('tab', { name: '签名与托管', exact: true }).click()
  // The signing tab saves only the wallet connection (no limits or paper-cost save here).
  check(await dialog.getByRole('button', { name: '保存并连接', exact: true }).count() === 1 && await dialog.getByRole('button', { name: /^保存(限额|模拟成本)/ }).count() === 0
    && (await dialog.getByRole('tabpanel').textContent()).includes('半托管'), 'signing tab shows assisted rules and only the wallet save action')
  await dialog.getByRole('tab', { name: '交易限额', exact: true }).click()
  check(await perOrder.inputValue() === String(before.riskLimits.maxOrderUsd + 1), 'switching tabs preserves the limits draft')
  await dialog.getByRole('button', { name: '保存限额', exact: true }).click()
  await page.waitForFunction((value) => window.__dhlStore.get().status?.riskLimits?.maxOrderUsd === value, before.riskLimits.maxOrderUsd + 1)
  await dialog.getByRole('button', { name: '恢复插件配置', exact: true }).click()
  await page.waitForFunction((value) => window.__dhlStore.get().status?.riskLimits?.maxOrderUsd === value, before.riskLimits.maxOrderUsd)
  check(true, 'limits save immediately and restore plugin configuration')
  // Allowed coins: 全部 / 手动设置
  const coinsMode = dialog.getByRole('radiogroup', { name: '允许开仓币对' })
  check(await coinsMode.getByRole('radio', { name: '手动设置', exact: true }).getAttribute('aria-checked') === 'true' && await dialog.getByRole('textbox', { name: /^币对/ }).isVisible(), 'a coin list opens in 手动设置 with its field')
  const manualList = await dialog.getByRole('textbox', { name: /^币对/ }).inputValue()
  await coinsMode.getByRole('radio', { name: '全部', exact: true }).click()
  check(await dialog.getByRole('textbox', { name: /^币对/ }).count() === 0, '全部 hides the coin field')
  await dialog.getByRole('button', { name: '保存限额', exact: true }).click()
  await page.waitForFunction(() => JSON.stringify(window.__dhlStore.get().status?.riskLimits?.allowedCoins) === '["*"]')
  check(true, '全部 saves as every market on the host')
  // Close and reopen: the saved 全部 shows, and 手动设置 still brings back the list.
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await menu(); await page.getByRole('button', { name: '交易限额与签名规则', exact: true }).click(); await dialog.waitFor()
  check(await coinsMode.getByRole('radio', { name: '全部', exact: true }).getAttribute('aria-checked') === 'true', 'reopening shows the saved 全部')
  await coinsMode.getByRole('radio', { name: '手动设置', exact: true }).click()
  check(await dialog.getByRole('textbox', { name: /^币对/ }).inputValue() === manualList, 'after a reopen, 手动设置 offers the last manual list')
  await dialog.getByRole('button', { name: '保存限额', exact: true }).click()
  await page.waitForFunction((list) => (window.__dhlStore.get().status?.riskLimits?.allowedCoins ?? []).join(', ') === list, manualList)
  check(true, '手动设置 saves the listed coins again')
  await dialog.getByRole('button', { name: '恢复插件配置', exact: true }).click().catch(() => {})
  const bounds = await dialog.boundingBox()
  check(bounds.y >= 0 && bounds.y + bounds.height <= 900, 'settings modal fits within the viewport')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  // Market picker: 可交易 / 全部 is kept when the category changes, and remembered
  const trigger = page.locator('.dhl-market-trigger')
  if (await trigger.count()) {
    const picker = () => page.locator('.dhl-picker')
    await trigger.first().click(); await picker().waitFor()
    const pressed = (name) => picker().getByRole('button', { name, exact: true }).first().getAttribute('aria-pressed')
    await picker().getByRole('button', { name: '可交易', exact: true }).click()
    await picker().locator('.dhl-picker-tabs').getByRole('button', { name: '现货', exact: true }).click()
    check(await pressed('可交易') === 'true', '可交易 stays selected after picking the 现货 category')
    // The market catalog loads over the network: wait for it before judging the list.
    await page.waitForFunction(() => !document.querySelector('.dhl-picker')?.innerText.includes('正在读取市场目录'), null, { timeout: 45_000 })
    check(await picker().locator('.dhl-picker-empty-action').isVisible(), 'a tradable-only empty category offers 查看全部 instead of switching on its own', { empty: await picker().locator('.dhl-picker-empty').allInnerTexts(), rows: await picker().locator('.dhl-picker-row').count(), body: (await picker().innerText()).slice(0, 400) })
    await picker().locator('.dhl-picker-tabs').getByRole('button', { name: 'HIP-3', exact: true }).click()
    check(await pressed('可交易') === 'true', '可交易 stays selected after picking HIP-3')
    await picker().getByRole('button', { name: '全部', exact: true }).first().click()
    await picker().locator('.dhl-picker-tabs').getByRole('button', { name: '永续', exact: true }).click()
    check(await pressed('全部') === 'true', '全部 stays selected after picking 永续')
    await page.keyboard.press('Escape'); await trigger.first().click(); await picker().waitFor()
    check(await pressed('全部') === 'true', 'the choice is remembered the next time the picker opens')
    await picker().getByRole('button', { name: '可交易', exact: true }).click()
    await page.keyboard.press('Escape')
  } else console.log('SKIP market picker: no market trigger on this page')
  check(errors.length === 0, 'settings interactions cause no page errors', errors)
  console.log('settings ok')
} finally { await browser.close() }
